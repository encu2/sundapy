import math

print("=== Testing math constants ===")
print("pi:", math.pi)
print("e:", math.e)
print("tau:", math.tau)
print("inf:", math.inf)
print("nan:", math.nan)

print("=== Testing trig & inverse trig ===")
print("sin(pi/2):", math.sin(math.pi / 2.0))
print("cos(0):", math.cos(0.0))
print("tan(pi/4):", math.tan(math.pi / 4.0))
print("asin(1):", math.asin(1.0))
print("acos(1):", math.acos(1.0))
print("atan(1):", math.atan(1.0))
print("atan2(1, 1):", math.atan2(1.0, 1.0))

print("=== Testing hyperbolic & inverse hyperbolic ===")
print("sinh(0):", math.sinh(0.0))
print("cosh(0):", math.cosh(0.0))
print("tanh(0):", math.tanh(0.0))
print("asinh(0):", math.asinh(0.0))
print("acosh(1):", math.acosh(1.0))
print("atanh(0):", math.atanh(0.0))

print("=== Testing powers, roots & logs ===")
print("sqrt(16):", math.sqrt(16.0))
print("pow(2, 3):", math.pow(2.0, 3.0))
print("exp(1):", math.exp(1.0))
print("log(e):", math.log(math.e))
print("log2(8):", math.log2(8.0))
print("log10(100):", math.log10(100.0))

print("=== Testing rounding & float ops ===")
print("floor(3.7):", math.floor(3.7))
print("ceil(3.2):", math.ceil(3.2))
print("trunc(3.9):", math.trunc(3.9))
print("round(3.5):", math.round(3.5))
print("fabs(-42.5):", math.fabs(-42.5))
print("hypot(3, 4):", math.hypot(3.0, 4.0))
print("copysign(5, -1):", math.copysign(5.0, -1.0))
print("radians(180):", math.radians(180.0))
print("degrees(pi):", math.degrees(math.pi))

print("=== Testing checks ===")
print("isnan(nan):", math.isnan(math.nan))
print("isinf(inf):", math.isinf(math.inf))
print("isfinite(42.0):", math.isfinite(42.0))

